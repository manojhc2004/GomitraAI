"""AI Chat API routes for Gomitra AI."""

from __future__ import annotations

import logging

from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field, field_validator

from app.api.auth import get_current_user
from app.database.models import User
from app.services.gemini_service import gemini_service

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/ai", tags=["AI Chat"])


class AIChatRequest(BaseModel):
    """Request payload for AI chat query."""

    message: str = Field(
        ...,
        description="The user's query or message regarding cattle/livestock farming.",
        min_length=1,
    )
    breed_context: str | None = Field(
        default=None,
        description="Optional cattle breed name context.",
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, value: str) -> str:
        """Validate and sanitize message input."""
        if not isinstance(value, str) or not value.strip():
            raise ValueError("Message cannot be empty or whitespace only.")
        return value.strip()

    @field_validator("breed_context")
    @classmethod
    def validate_breed_context(cls, value: str | None) -> str | None:
        """Sanitize breed_context input."""
        if value is None:
            return None
        if isinstance(value, str):
            cleaned = value.strip()
            return cleaned if cleaned else None
        return None


class AIChatResponse(BaseModel):
    """Response payload for AI chat query."""

    response: str = Field(..., description="Plain text AI response generated by Gemini AI.")


@router.post(
    "/chat",
    response_model=AIChatResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate Gomitra AI response",
    description="Protected endpoint to query Gomitra AI about cattle, livestock, or breed specific information.",
)
def chat(
    payload: AIChatRequest,
    current_user: User = Depends(get_current_user),
) -> AIChatResponse:
    """Generate response from GeminiService for authenticated user.

    Args:
        payload: Validated request containing message and optional breed_context.
        current_user: Authenticated User object resolved from Bearer JWT.

    Returns:
        AIChatResponse with plain text response string.

    Raises:
        HTTPException: If an unexpected error occurs during AI response generation.
    """
    logger.info("Received AI chat request from user_id=%s", current_user.id)

    try:
        response_text = gemini_service.generate_response(
            message=payload.message,
            breed_context=payload.breed_context,
        )
        return AIChatResponse(response=response_text)
    except Exception as exc:
        logger.exception("Failed to process AI chat request for user_id=%s", current_user.id)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while generating the AI response.",
        ) from exc
